import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:beleka_pos/screens/login_screen.dart';

void main() {
  testWidgets('Beleka POS LoginScreen renders adaptively', (WidgetTester tester) async {
    tester.view.physicalSize = const Size(1280, 800);
    tester.view.devicePixelRatio = 1.0;
    addTearDown(tester.view.resetPhysicalSize);
    addTearDown(tester.view.resetDevicePixelRatio);

    await tester.pumpWidget(
      const ProviderScope(
        child: MaterialApp(
          home: LoginScreen(),
        ),
      ),
    );

    await tester.pumpAndSettle();

    // Verify that the login terminal renders
    expect(find.text('TERMINAL AUTHENTICATION'), findsOneWidget);
    expect(find.text('PIN PAD'), findsOneWidget);
  });
}
